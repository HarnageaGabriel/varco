"""Generate the README terminal art for `varco run`.

The text is the real table report golden (testdata/run/table.golden), taken
verbatim and wrapped at a terminal column width, drawn in a rounded terminal
window with the varco palette from logo_gen.py. Python 3 standard library
only; no external fonts, images or network access.

Usage: python tools/branding/readme_art.py
Writes docs/assets/readme-run-report.svg (light) and
docs/assets/readme-run-report-dark.svg (dark).
"""
import os
import xml.sax.saxutils as xml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GOLDEN = os.path.join(ROOT, "testdata", "run", "table.golden")
OUTDIR = os.path.join(ROOT, "docs", "assets")

COLS = 100
FONT = "'JetBrains Mono','SFMono-Regular',Menlo,Consolas,'Liberation Mono',monospace"
FONT_SIZE = 11
CHAR_W = 6.6
LINE_H = 17
PAD = 16
BAR = 30

LIGHT = {
    "ink": "#10294F",
    "muted": "#4A5A73",
    "window": "#FFFFFF",
    "border": "#D5DEEA",
    "titlebar": "#F4F7FB",
    "accent": "#1A5FC4",
    "teal": "#16BFA0",
}
DARK = {
    "ink": "#F2F5FA",
    "muted": "#AFC0D8",
    "window": "#0D1117",
    "border": "#30363D",
    "titlebar": "#161B22",
    "accent": "#4A93FF",
    "teal": "#2DD4B3",
}


def wrap(line, cols):
    if not line:
        return [""]
    return [line[i : i + cols] for i in range(0, len(line), cols)]


def report_lines():
    with open(GOLDEN, encoding="utf-8") as f:
        lines = f.read().replace("\r\n", "\n").rstrip("\n").split("\n")
    return [row for line in lines for row in wrap(line, COLS)]


def svg(palette, lines):
    width = int(COLS * CHAR_W + 2 * PAD)
    body = BAR + PAD + len(lines) * LINE_H + PAD
    parts = [
        f"<!-- generated by tools/branding/readme_art.py from testdata/run/table.golden ({len(lines)} rendered rows) -->",
        (
            f'<rect x="0.5" y="0.5" width="{width - 1}" height="{body - 1}" rx="10" '
            f'fill="{palette["window"]}" stroke="{palette["border"]}"/>'
        ),
        (
            f'<path d="M0.5 10.5C0.5 4.98 4.98 0.5 10.5 0.5h{width - 21}c5.52 0 10 4.48 10 10v{BAR - 10.5}H0.5z" '
            f'fill="{palette["titlebar"]}"/>'
        ),
    ]
    dot_x, dot_r = PAD + 4, 4
    for i, color in enumerate((palette["accent"], palette["muted"], palette["teal"])):
        parts.append(f'<circle cx="{dot_x + i * 14}" cy="{BAR / 2}" r="{dot_r}" fill="{color}"/>')
    parts.append(
        f'<text x="{width / 2}" y="{BAR / 2 + 4}" text-anchor="middle" font-family="{FONT}" '
        f'font-size="{FONT_SIZE}" fill="{palette["muted"]}">varco run</text>'
    )
    for i, text in enumerate(lines):
        color = palette["ink"] if text.strip() else palette["muted"]
        y = BAR + PAD + (i + 1) * LINE_H - 4
        parts.append(
            f'<text x="{PAD}" y="{y}" xml:space="preserve" font-family="{FONT}" '
            f'font-size="{FONT_SIZE}" fill="{color}">{xml.escape(text)}</text>'
        )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {body}" role="img" '
        f'aria-label="varco run report: table output with the verdict, coverage and per-case differences">'
        f"<title>varco run report</title>{''.join(parts)}</svg>\n"
    )


def main():
    lines = report_lines()
    os.makedirs(OUTDIR, exist_ok=True)
    for name, palette in (
        ("readme-run-report.svg", LIGHT),
        ("readme-run-report-dark.svg", DARK),
    ):
        with open(os.path.join(OUTDIR, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(svg(palette, lines))
    print(f"ok: {len(lines)} rendered rows -> {OUTDIR}")


if __name__ == "__main__":
    main()
