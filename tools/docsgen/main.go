// Command docsgen renders Markdown pages from the diagnostic registry.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/HarnageaGabriel/varco/internal/diag"
)

func main() {
	out := flag.String("out", "docs/diagnostics", "output directory")
	check := flag.Bool("check", false, "check generated output without writing")
	flag.Parse()
	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "docsgen:", err)
		os.Exit(1)
	}
}

func run(out string, check bool) error {
	pages := render(diag.List())
	if check {
		return verify(out, pages)
	}
	return write(out, pages)
}

func render(entries []diag.Entry) map[string][]byte {
	sort.Slice(entries, func(i, j int) bool { return entries[i].Code < entries[j].Code })
	pages := make(map[string][]byte, len(entries)+1)
	var index strings.Builder
	index.WriteString("<!-- Code generated by tools/docsgen; DO NOT EDIT. -->\n\n# Diagnostic codes\n\n| Code | Severity | Title |\n|---|---|---|\n")
	for _, entry := range entries {
		fmt.Fprintf(&index, "| [%s](%s.md) | %s | %s |\n", entry.Code, entry.Code, entry.Severity, entry.Title)
		pages[string(entry.Code)+".md"] = []byte(renderPage(entry))
	}
	pages["README.md"] = []byte(index.String())
	return pages
}

func renderPage(entry diag.Entry) string {
	return fmt.Sprintf(`<!-- Code generated by tools/docsgen; DO NOT EDIT. -->

# %s: %s

- Severity: %s
- Area: %s

## Description

%s

## Remediation

%s
`, entry.Code, entry.Title, entry.Severity, entry.Area, entry.Description, entry.Remediation)
}

func write(out string, pages map[string][]byte) error {
	if err := os.MkdirAll(out, 0o700); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	existing, err := filepath.Glob(filepath.Join(out, "*.md"))
	if err != nil {
		return fmt.Errorf("list generated docs: %w", err)
	}
	for _, path := range existing {
		if _, ok := pages[filepath.Base(path)]; !ok {
			if err := os.Remove(path); err != nil {
				return fmt.Errorf("remove stale page %s: %w", filepath.Base(path), err)
			}
		}
	}
	for _, name := range sortedNames(pages) {
		if err := os.WriteFile(filepath.Join(out, name), pages[name], 0o600); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
	}
	return nil
}

func verify(out string, pages map[string][]byte) error {
	var drift []string
	for _, name := range sortedNames(pages) {
		content, err := os.ReadFile(filepath.Join(out, name)) //nolint:gosec // names come from the static registry
		if err != nil || !bytes.Equal(normalize(content), pages[name]) {
			drift = append(drift, name)
		}
	}
	existing, err := filepath.Glob(filepath.Join(out, "*.md"))
	if err != nil {
		return fmt.Errorf("list generated docs: %w", err)
	}
	for _, path := range existing {
		if _, ok := pages[filepath.Base(path)]; !ok {
			drift = append(drift, filepath.Base(path)+" (stale)")
		}
	}
	if len(drift) != 0 {
		sort.Strings(drift)
		return fmt.Errorf("generated docs out of date (run `make docs`): %s", strings.Join(drift, ", "))
	}
	return nil
}

func sortedNames(pages map[string][]byte) []string {
	names := make([]string, 0, len(pages))
	for name := range pages {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func normalize(content []byte) []byte {
	return bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n"))
}
